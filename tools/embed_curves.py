#!/usr/bin/env python3
"""Makes crates/joseon-headphones/src/embedded_curves.rs from the macOS app's EmbeddedCurves.swift.

The curve data is AutoEq measurement data (MIT). This script copies the numbers as text, so the
Rust file holds exactly the values of the Swift file.

    python3 tools/embed_curves.py /path/to/Joseon/Sources/JoseonHeadphones/EmbeddedCurves.swift
"""
import re
import sys

source = open(sys.argv[1], encoding="utf-8").read()


def numbers(block):
    return [n for n in re.split(r"[\s,]+", block.strip()) if n]


def as_f32(text):
    return text if ("." in text or "e" in text.lower()) else text + ".0"


def rows(values, indent="    "):
    lines, line = [], indent
    for v in values:
        piece = as_f32(v) + ", "
        if len(line) + len(piece) > 118:
            lines.append(line.rstrip())
            line = indent
        line += piece
    lines.append(line.rstrip())
    return "\n".join(lines)


grid = numbers(re.search(r"standardFrequenciesHz: \[Float\] = \[(.*?)\]", source, re.S).group(1))
assert len(grid) == 200, len(grid)

curves = []
pattern = re.compile(
    r"((?:    ///[^\n]*\n)+)    public static let (\w+) = HeadphoneCurve\(\s*name: \"([^\"]*)\",\s*source: \"([^\"]*)\","
    r"\s*frequenciesHz: standardFrequenciesHz,\s*levelsDB: \[(.*?)\]\s*\)",
    re.S,
)
for docs, ident, name, src, levels in pattern.findall(source):
    values = numbers(levels)
    assert len(values) == 200, (ident, len(values))
    curves.append((docs, ident, name, src, values))

headphones = numbers(re.search(r"static let headphones: \[HeadphoneCurve\] = \[(.*?)\]", source, re.S).group(1))
targets = numbers(re.search(r"static let targets: \[HeadphoneCurve\] = \[(.*?)\]", source, re.S).group(1))
assert len(curves) == len(headphones) + len(targets) == 22, (len(curves), len(headphones), len(targets))


def const_name(ident):
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", ident).upper()


header = source[: source.index("import Foundation")]
header = header.replace("// Generated from AutoEq measurement data on 2026-09-20. Do not edit by hand.",
                        "// Generated by tools/embed_curves.py from the macOS app's EmbeddedCurves.swift, which was\n"
                        "// generated from AutoEq measurement data on 2026-09-20. Do not edit by hand.")
out = [header.rstrip("\n").replace("//", "//!", 1) if False else header.rstrip("\n")]
out.append("""
//! Measured headphone responses and target curves compiled into the binary.
//!
//! No resource file: the crate ships the curves as source on purpose.

// The numbers are measurements, written as the source data writes them. A level
// of 3.14 dB is not pi, and "15150.50" keeps its two decimals.
#![allow(clippy::approx_constant, clippy::excessive_precision)]

use crate::curve::HeadphoneCurve;

/// Points in every embedded curve.
pub const POINT_COUNT: usize = 200;

/// The shared 200-point log-spaced frequency grid, 20 Hz ... 20000 Hz.
#[rustfmt::skip]
pub const STANDARD_FREQUENCIES_HZ: [f32; POINT_COUNT] = [
""" + rows(grid) + """
];

/// One curve of the embedded data.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct EmbeddedCurve {
    pub name: &'static str,
    pub source: &'static str,
    /// Raw level in dB on `STANDARD_FREQUENCIES_HZ`.
    pub levels_db: &'static [f32; POINT_COUNT],
}

impl EmbeddedCurve {
    /// The curve as an owned value.
    pub fn curve(&self) -> HeadphoneCurve {
        HeadphoneCurve {
            name: self.name.to_string(),
            source: self.source.to_string(),
            frequencies_hz: STANDARD_FREQUENCIES_HZ.to_vec(),
            levels_db: self.levels_db.to_vec(),
        }
    }
}
""")
for docs, ident, name, src, values in curves:
    doc = "\n".join(line.strip() for line in docs.strip().split("\n"))
    out.append(f"""
{doc}
#[rustfmt::skip]
pub const {const_name(ident)}: EmbeddedCurve = EmbeddedCurve {{
    name: "{name}",
    source: "{src}",
    levels_db: &[
{rows(values, "        ")}
    ],
}};
""".rstrip("\n"))
    out.append("")

out.append("/// Every embedded headphone response, in display order.")
out.append(f"pub const HEADPHONES: [EmbeddedCurve; {len(headphones)}] = [")
out += [f"    {const_name(h)}," for h in headphones]
out.append("];\n")
out.append("/// Every embedded target curve, in display order.")
out.append(f"pub const TARGETS: [EmbeddedCurve; {len(targets)}] = [")
out += [f"    {const_name(t)}," for t in targets]
out.append("];")
sys.stdout.write("\n".join(out) + "\n")
